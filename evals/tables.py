#: The columns of the filter table, in order: (group|language) as the cases record them.
GROUP_COLUMNS = (
    "inyeccion_publica|en",
    "inyeccion_publica|es",
    "ataque_a_leads|es",
    "mensaje_normal|en",
    "mensaje_normal|es",
    "lead_normal|es",
    "correo_legitimo_real|es",
)


class ResultsError(ValueError):
    """The saved records are not what the tables expect."""


def tx(lang: str, key: str, **fields: object) -> str:
    return TEXT[lang][key].format(**fields)


def pct(value: float | None, lang: str) -> str:
    """A percentage: ``87,5 %`` in Spanish, ``87.5%`` in English."""
    if value is None:
        return tx(lang, "n/a")
    number = f"{value * 100:.1f}"
    return number.replace(".", ",") + " %" if lang == "es" else number + "%"


def decimal(value: float, lang: str, digits: int = 3) -> str:
    number = f"{value:.{digits}f}"
    return number.replace(".", ",") if lang == "es" else number


def pct_ci(p: dict, lang: str) -> str:
    """A proportion with its counts and its 95 % confidence interval."""
    if not p["n"]:
        return tx(lang, "n/a")
    low, high = p["ic95"]
    interval = tx(lang, "ci", low=pct(low, lang), high=pct(high, lang))
    return f"{pct(p['valor'], lang)} ({p['k']}/{p['n']}; {interval})"


def export_bot(records_folder: Path) -> None:
    """Turn the Inspect logs into compact files, one per model and defense.

    If a condition was run several times, every run goes into the same file, numbered in the
    ``corrida`` field in the order they ran. Old logs saved the task arguments with Spanish
    names (``defensa``, ``particion``); both spellings are read.
    """
    from inspect_ai.log import list_eval_logs, read_eval_log

    groups: dict[tuple[str, str, str], list] = defaultdict(list)
    for info in list_eval_logs(str(records_folder)):
        record = read_eval_log(info)
        if record.status != "success" or not record.samples:
            continue
        model = record.eval.model.split("/")[-1]
        args = record.eval.task_args
        defense = legacy_v1.defense(legacy_v1.task_arg(args, "defense", "ninguna"))
        split = legacy_v1.task_arg(args, "split", "test")
        groups[(split, model, defense)].append(record)

    for (split, model, defense), records in groups.items():
        rows = []
        for run, record in enumerate(sorted(records, key=lambda r: r.eval.created), 1):
            for sample in record.samples:
                score = sample.scores["resultado"]
                rows.append(
                    {
                        "corrida": run,
                        "id": sample.id,
                        "tipo": score.metadata["tipo"],
                        "tecnica": score.metadata.get("tecnica"),
                        "esperada": sample.target,
                        "salida": score.answer,
                        "motivo": score.metadata.get("motivo"),
                        "ataque_exitoso": bool(score.metadata.get("ataque_exitoso")),
                    }
                )
        write_jsonl(RESULTS / "bot" / split / f"{model}__{defense}.jsonl", rows)


def build_filter_table(split: str, lang: str) -> tuple[list[str], dict]:
    folder = RESULTS / "filter" / split
    if not folder.exists():
        return [], {}
    cases = {c["id"]: c for c in read_jsonl(folder / "casos.jsonl")}
    present = {f.stem for f in folder.glob("*.jsonl")} - {"casos"}
    unknown = sorted(present - set(legacy_v1.DETECTORS))
    if unknown:
        raise ResultsError(f"{folder}: unknown detector file(s): {unknown}")
    missing = sorted(legacy_v1.EXPECTED_DETECTORS.get(split, frozenset()) - present)
    if missing:
        raise ResultsError(f"{folder}: missing detector file(s): {missing}")
    data: dict = {}
    for detector in legacy_v1.DETECTORS:
        responses = read_jsonl(folder / f"{detector}.jsonl")
        if not responses:
            continue
        tally: dict[str, list[int]] = defaultdict(lambda: [0, 0])
        for r in responses:
            case = cases.get(r["id"])
            if case is None:
                raise ResultsError(f"{folder}/{detector}.jsonl: unknown case id {r['id']!r}")
            if not isinstance(r["marcado"], bool):
                raise ResultsError(
                    f"{folder}/{detector}.jsonl: {r['id']!r}: 'marcado' is not a bool"
                )
            key = f"{legacy_v1.group(case['grupo'])}|{case['idioma']}"
            if key not in GROUP_COLUMNS:
                raise ResultsError(f"{folder}/casos.jsonl: unknown group/language {key!r}")
            tally[key][0] += int(r["marcado"])
            tally[key][1] += 1
        data[detector] = {key: proportion(k, n) for key, (k, n) in tally.items()}
    if not data:
        return [], {}
    columns = [c for c in GROUP_COLUMNS if any(c in d for d in data.values())]
    header = tx(lang, "filter.header")
    lines = [
        f"| {header} | " + " | ".join(tx(lang, f"group.{c}") for c in columns) + " |",
        "|---|" + "---|" * len(columns),
    ]
    for detector, per_group in data.items():
        cells = [
            f"{pct(per_group[c]['valor'], lang)} ({per_group[c]['k']}/{per_group[c]['n']})"
            if c in per_group
            else tx(lang, "n/a")
            for c in columns
        ]
        lines.append(f"| {tx(lang, f'detector.{detector}')} | " + " | ".join(cells) + " |")
    return lines, data


def build_bot_table(split: str, lang: str) -> tuple[list[str], dict]:
    data: dict = {}
    folder = RESULTS / "bot" / split
    for file in sorted(folder.glob("*.jsonl")):
        parts = file.stem.split("__")
        if len(parts) != 2:
            raise ResultsError(f"{file}: the name must be <model>__<defense>.jsonl")
        model, defense = parts[0], legacy_v1.defense(parts[1])
        rows = read_jsonl(file)
        kinds = {f["tipo"] for f in rows}
        if not kinds <= {"ataque", "normal"}:
            raise ResultsError(f"{file}: unknown message type(s): {sorted(kinds)}")
        attacks = [f for f in rows if f["tipo"] == "ataque"]
        normals = [f for f in rows if f["tipo"] == "normal"]
        runs = sorted({f.get("corrida", 1) for f in rows})
        data[f"{model}|{defense}"] = {
            "modelo": model,
            "defensa": defense,
            "corridas": len(runs),
            "ataque_exitoso": proportion(sum(f["ataque_exitoso"] for f in attacks), len(attacks)),
            "ataque_exitoso_por_corrida": [
                sum(f["ataque_exitoso"] for f in attacks if f.get("corrida", 1) == c) for c in runs
            ],
            "ataques_por_corrida": len(attacks) // len(runs) if runs else 0,
            "normales_bien": proportion(
                sum(f["salida"] == f["esperada"] for f in normals), len(normals)
            ),
            "normales_a_revision": proportion(
                sum(f["salida"] == legacy_v1.HUMAN_REVIEW for f in normals), len(normals)
            ),
            "ataques_a_revision": proportion(
                sum(f["salida"] == legacy_v1.HUMAN_REVIEW for f in attacks), len(attacks)
            ),
        }
    if not data:
        return [], {}
    lines = [tx(lang, "bot.header"), "|---|---|---|---|---|---|---|"]
    order = {d: i for i, d in enumerate(legacy_v1.DEFENSES)}
    for d in sorted(data.values(), key=lambda d: (d["modelo"], order[d["defensa"]])):
        per_run = ", ".join(str(k) for k in d["ataque_exitoso_por_corrida"])
        per_run = tx(lang, "bot.per_run", runs=per_run, total=d["ataques_por_corrida"])
        defense_name = tx(lang, f"defense.{d['defensa']}")
        lines.append(
            f"| {d['modelo']} | {defense_name} | {d['corridas']} | "
            f"{pct_ci(d['ataque_exitoso'], lang)} | {per_run} | "
            f"{pct_ci(d['normales_bien'], lang)} | {pct_ci(d['normales_a_revision'], lang)} |"
        )
    return lines, data


def build_phishing_table(lang: str) -> tuple[list[str], dict]:
    file = RESULTS / "phishing" / "resumen.json"
    if not file.exists():
        return [], {}
    r = json.loads(file.read_text(encoding="utf-8"))
    d = r["deteccion"]
    lines = [
        tx(lang, "phishing.intro", emails=r["correos"], phishing=r["phishing"]),
        "",
        tx(lang, "phishing.header"),
        "|---|---|---|---|---|",
    ]
    for key, name in (
        ("base_tfidf", tx(lang, "phishing.baseline")),
        ("modelo", tx(lang, "phishing.model", model=r["modelo"])),
    ):
        m = d[key]
        lines.append(
            f"| {name} | {pct(m['aciertos']['valor'], lang)} | {pct(m['precision'], lang)} | "
            f"{pct(m['cobertura'], lang)} | {decimal(m['f1'], lang)} |"
        )
    lines += ["", tx(lang, "tricks.header"), "|---|---|---|---|"]
    for trick, t in r["trucos"].items():
        name = TEXT[lang].get(f"trick.{trick}", trick)
        lines.append(
            f"| {name} | {pct(t['frecuencia'], lang)} | {decimal(t['f1_modelo'], lang)} | "
            f"{decimal(t['f1_mayoria'], lang)} |"
        )
    return lines, r


def build_review_table(lang: str) -> tuple[list[str], dict]:
    file = RESULTS / "review" / "resumen.json"
    if not file.exists():
        return [], {}
    r = json.loads(file.read_text(encoding="utf-8"))
    fraud, legitimate = r["phishing"], r["legitimos"]

    def cell(d: dict, key: str) -> str:
        m = d[key]
        return f"{pct(m['valor'], lang)} ({m['k']}/{m['n']})"

    def row(name: str, key: str) -> str:
        return f"| {name} | {cell(fraud, key)} | {cell(legitimate, key)} |"

    def active(d: dict) -> str:
        links = d["enlaces_activos"]
        return tx(lang, "review.active_cell", after=links["despues"], before=links["antes"])

    lines = [
        tx(
            lang,
            "review.intro",
            emails=r["correos"],
            phishing=fraud["correos"],
            legitimate=legitimate["correos"],
        ),
        "",
        tx(lang, "review.header"),
        "|---|---|---|",
        f"| {tx(lang, 'review.active_links')} | {active(fraud)} | {active(legitimate)} |",
        row(tx(lang, "review.hidden_destination"), "con_destino_oculto"),
        row(tx(lang, "review.names_ask"), "con_pedido"),
        row(tx(lang, "review.names_pressure"), "con_presion"),
        row(tx(lang, "review.second_person"), "exige_segunda_persona"),
        (
            f"| {tx(lang, 'review.same_words')} | {pct(fraud['palabras_iguales']['valor'], lang)} | "
            f"{pct(legitimate['palabras_iguales']['valor'], lang)} |"
        ),
        "",
        tx(lang, "review.hints_header"),
        "|---|---|---|",
    ]
    for group, prefix, name_of in (
        ("por_pedido", tx(lang, "review.asks"), lambda p: f"ask.{legacy_v1.ask_id(p)}"),
        (
            "por_presion",
            tx(lang, "review.pressure"),
            lambda p: f"pressure.{legacy_v1.pressure_id(p)}",
        ),
    ):
        for phrase in sorted(set(fraud[group]) | set(legitimate[group])):
            cells = [
                cell(d[group], phrase) if phrase in d[group] else pct(0.0, lang)
                for d in (fraud, legitimate)
            ]
            lines.append(f"| {prefix}: {tx(lang, name_of(phrase))} | " + " | ".join(cells) + " |")
    return lines, r


def render(split: str, lang: str) -> tuple[str, dict]:
    """The tables of ``split`` as Markdown in ``lang``, and the data behind them."""
    filter_lines, filter_data = build_filter_table(split, lang)
    bot, bot_data = build_bot_table(split, lang)
    phishing, phishing_data = build_phishing_table(lang)
    review_lines, review_data = build_review_table(lang)
    parts = [tx(lang, "title"), "", tx(lang, "intro", split=split)]
    if bot:
        parts += ["", tx(lang, "bot.heading"), "", *bot]
    if filter_lines:
        parts += ["", tx(lang, "filter.heading"), "", tx(lang, "filter.note"), "", *filter_lines]
    if phishing:
        parts += ["", tx(lang, "phishing.heading"), "", *phishing]
    if review_lines:
        parts += ["", tx(lang, "review.heading"), "", *review_lines]
    data = {
        "filtro": filter_data,
        "bot": bot_data,
        "phishing": phishing_data,
        "revision": review_data,
    }
    return "\n".join(parts) + "\n", data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--export-bot", type=Path, help="folder with Inspect logs")
    parser.add_argument("--split", default="test")
    parser.add_argument(
        "--lang", choices=LANGS, default="en", help="language of the printed tables"
    )
    args = parser.parse_args(argv)
    if args.export_bot:
        export_bot(args.export_bot)

    stem = "summary" if args.split == "test" else f"summary-{args.split}"
    markdown = {}
    for lang in LANGS:
        markdown[lang], data = render(args.split, lang)
    (RESULTS / f"{stem}.md").write_text(markdown["en"], encoding="utf-8")
    (RESULTS / f"{stem}.es.md").write_text(markdown["es"], encoding="utf-8")
    (RESULTS / f"{stem}.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(markdown[args.lang])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
