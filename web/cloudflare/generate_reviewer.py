"""Write src/reviewer.js with the reviewer's instructions, schema and trick descriptions.

The website's Worker uses the same reviewer as the library (LLMDetector). This script copies
the texts from Python so they do not drift apart; a test checks that they match:

    uv run python web/cloudflare/generate_reviewer.py

The instructions and the schema are Spanish on purpose: they are what the measurements were
made with. The trick descriptions are the Spanish ones of the catalog, for the Worker's notice.
"""

import json
from pathlib import Path

from centinela.catalog import t
from centinela.detectors.llm import INSTRUCTIONS, SCHEMA
from centinela.verdict import TRICKS

DESTINATION = Path(__file__).resolve().parent / "src" / "reviewer.js"


def _js(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def content() -> str:
    tricks = {trick: t(f"trick.{trick}", "es") for trick in TRICKS}
    return (
        "// Generated by `uv run python web/cloudflare/generate_reviewer.py` from\n"
        "// src/centinela/detectors/llm.py and src/centinela/catalog.py. Do not edit it by hand:\n"
        "// a Python test checks that it matches the library.\n"
        f"export const INSTRUCCIONES = {_js(INSTRUCTIONS)};\n\n"
        f"export const ESQUEMA = {_js(SCHEMA)};\n\n"
        f"export const TRUCOS = {_js(tricks)};\n"
    )


if __name__ == "__main__":
    DESTINATION.parent.mkdir(exist_ok=True)
    DESTINATION.write_text(content(), encoding="utf-8")
    print(f"Written {DESTINATION}")
